/**
 * The plugin: loads the content folder, builds a pack per bundle, serves them,
 * and hands players the bundle they should be holding.
 *
 * <p>Thin on purpose. Everything it does is assembled from pieces that work
 * without a server, so this class is wiring and console output rather than
 * logic. If something here starts making decisions, that is the signal it
 * belongs one layer down where it can be tested.
 *
 * <p><strong>The plugin name is load-bearing and cannot change.</strong>
 * Persistent-data keys are namespaced by it, so a rename would orphan
 * everything placed in every world by every earlier version.
 */
public final class RPEnginePlugin extends JavaPlugin implements Listener {

    /** So the output folder can answer "is this mine?" without anybody asking. */
    private static final String OUTPUT_README = """
            Everything in this folder is generated by RP Engine.

            Your content goes in ../content/, one folder per pack. This folder holds
            the resource packs built from it, one zip per bundle. Editing a zip here
            does nothing: the next reload overwrites it.

            Safe to delete. It is rebuilt on the next start.
            """;

    private final ContentRegistryImpl registry = new ContentRegistryImpl();
    private final BundleSessions sessions = new BundleSessions();
    private ItemsImpl items;
    private ModelPlacementListener placements;
    private Recipes recipes;
    /** Recipes are outside the id space, so this is the only list of them. */
    private List<ContentId> recipeIds = List.of();
    private final SoundsImpl sounds = new SoundsImpl();
    private final IconsImpl icons = new IconsImpl();
    private final Overlays overlays = new Overlays();

    private PackHost host;
    private PackDelivery delivery;
    private List<BuiltPack> built = List.of();
    private String defaultBundle = "";

    @Override
    public void onEnable() {
        saveDefaultConfig();
        items = new ItemsImpl(this);
        placements = new ModelPlacementListener(this, items);
        recipes = new Recipes(this, items);
        getServer().getPluginManager().registerEvents(this, this);
        getServer().getPluginManager().registerEvents(placements, this);
        startHost();
        rebuild(getServer().getConsoleSender());
    }

    @Override
    public void onDisable() {
        // Recipes live in the server's registry rather than ours, so leaving
        // them behind would outlast the plugin that made them.
        if (recipes != null) {
            recipes.clear();
        }
        if (host != null) {
            host.stop();
        }
    }

    /** What this server holds. The supported way in for another plugin. */
    public ContentRegistry registry() {
        return registry;
    }

    /** The icons this server holds, and the way to put one into text. */
    public ai.resourcepack.engine.api.Icons icons() {
        return icons;
    }

    /** The custom sounds this server holds. */
    public ai.resourcepack.engine.api.Sounds sounds() {
        return sounds;
    }

    /** The custom items this server holds. */
    public Items items() {
        return items;
    }

    private void startHost() {
        defaultBundle = getConfig().getString("default-bundle", "");
        String address = getConfig().getString("host.public-address", "http://127.0.0.1:8181");
        host = new PackHost(address);
        delivery = new PackDelivery(sessions, host,
                getConfig().getString("prompt.message", ""),
                getConfig().getBoolean("prompt.force", false));

        if (!getConfig().getBoolean("host.enabled", true)) {
            getLogger().info("Pack hosting is off. Packs are built but not served.");
            return;
        }
        try {
            int port = host.start(getConfig().getInt("host.port", 8181));
            getLogger().info("Serving packs on port " + port + " as " + address);
        } catch (IOException e) {
            getLogger().warning("Could not listen on port " + getConfig().getInt("host.port", 8181)
                    + ": " + e.getMessage() + ". Packs are built but not served.");
        }
    }

    /**
     * Reads the content folder, builds every bundle, and re-serves them.
     *
     * <p>Everything is rebuilt rather than diffed. A namespace is replaced
     * whole or not at all, and the same reasoning applies here: a partial
     * rebuild is how the registry ends up disagreeing with the zip somebody is
     * holding.
     */
    private void rebuild(CommandSender to) {
        // content/ is yours and output/ is ours. The names are doing real work
        // here: a folder called packs/ reads as "put your packs in me", which is
        // the one mistake a new user is most likely to make on day one.
        Path content = getDataFolder().toPath().resolve("content");
        Path output = getDataFolder().toPath().resolve("output");
        try {
            Files.createDirectories(content);
            Files.createDirectories(output);
            Files.writeString(output.resolve("README.txt"), OUTPUT_README);
        } catch (IOException e) {
            to.sendMessage("[RPEngine] Could not prepare " + getDataFolder() + ": " + e.getMessage());
            return;
        }

        // Everything goes, then the folder is read again. See clear().
        registry.clear();

        LoadReport loaded = new ContentFolderLoader(registry).load(content, ContentSource.AUTHORED);
        report(to, "content", loaded.diagnostics());

        ItemDefinitions.Result parsedItems = ItemDefinitions.parse(loaded);
        report(to, "items", parsedItems.diagnostics());
        // Needs a running server, so it lives out here rather than in parse().
        report(to, "items", ItemDefinitions.checkGivable(parsedItems));
        items.replace(parsedItems.items());

        ModelDefinitions.Result parsedModels =
                ModelDefinitions.parse(loaded, parsedItems.items(), measure(content, parsedItems));
        report(to, "model", parsedModels.diagnostics());
        placements.replace(parsedModels.model());

        SoundDefinitions.Result parsedSounds = SoundDefinitions.parse(loaded);
        report(to, "sounds", parsedSounds.diagnostics());
        sounds.replace(parsedSounds.sounds());

        IconDefinitions.Result parsedIcons = IconDefinitions.parse(loaded);
        report(to, "icons", parsedIcons.diagnostics());
        icons.replace(parsedIcons.icons());

        OverlayDefinitions.Result parsedScreens = OverlayDefinitions.screens(loaded);
        OverlayDefinitions.Result parsedHuds = OverlayDefinitions.huds(loaded);
        report(to, "screens", parsedScreens.diagnostics());
        report(to, "huds", parsedHuds.diagnostics());
        overlays.replace(parsedScreens.overlays(), parsedHuds.overlays());

        BuildReport builtReport = new PackBuilder(
                getConfig().getInt("pack.format", PackBuilder.PACK_FORMAT),
                getConfig().getString("pack.description", "RP Engine"))
                .with(new ItemAssets())
                .with(new SoundAssets())
                .with(new FontAssets())
                .build(content, output, loaded);
        report(to, "build", builtReport.diagnostics());

        // After the items exist, because a recipe's ingredients and result are
        // resolved against them.
        RecipeDefinitions.Result parsedRecipes = RecipeDefinitions.parse(loaded);
        report(to, "recipes", parsedRecipes.diagnostics());
        recipeIds = List.copyOf(parsedRecipes.recipes().keySet());
        for (String problem : recipes.replace(parsedRecipes.recipes())) {
            getLogger().warning("recipe " + problem);
        }

        built = builtReport.packs();
        for (BuiltPack pack : built) {
            host.register(pack);
        }

        to.sendMessage("[RPEngine] " + plural(loaded.packs().size(), "pack") + ", "
                + plural(loaded.definitions().size(), "definition") + ", "
                + plural(built.size(), "bundle") + " built, "
                + plural(recipes.size(), "recipe") + ".");

        // Everybody online is holding a pack that may no longer exist, so they
        // are re-sent before they notice. Nothing is sent to a player whose
        // stack is already right.
        for (Player player : getServer().getOnlinePlayers()) {
            delivery.apply(player, desiredFor(player));
        }
    }

    /**
     * Measures every item that has a model, so placed model can default its
     * hitbox to what you can actually see.
     *
     * <p>Reads the geometry a second time, which the builder also does. Worth
     * it: threading measurements out of the build would put the pack builder
     * in the business of telling the placed model layer things, and these files
     * are small and read once per reload.
     */
    private java.util.Map<ai.resourcepack.engine.api.ContentId, ai.resourcepack.engine.core.item.Geometry.Bounds>
            measure(Path content, ItemDefinitions.Result parsed) {
        java.util.Map<ai.resourcepack.engine.api.ContentId,
                ai.resourcepack.engine.core.item.Geometry.Bounds> measured = new java.util.HashMap<>();
        for (ai.resourcepack.engine.api.ItemInfo item : parsed.items().values()) {
            String name = item.model().orElse(null);
            if (name == null) {
                continue;
            }
            Path file = content.resolve(item.id().namespace())
                    .resolve("assets").resolve("models").resolve(name + ".json");
            if (!Files.isRegularFile(file)) {
                continue;
            }
            try {
                ai.resourcepack.engine.core.item.Geometry
                        .read(Files.readAllBytes(file), item.id().namespace())
                        .ifPresent(model -> measured.put(item.id(), model.bounds()));
            } catch (IOException e) {
                // The builder reports this properly. Failing to measure just
                // means the hitbox falls back to one block.
                getLogger().fine("Could not measure " + item.id() + ": " + e.getMessage());
            }
        }
        return measured;
    }

    private void report(CommandSender to, String stage, List<Diagnostic> diagnostics) {
        for (Diagnostic diagnostic : diagnostics) {
            // The logger adds its own [RPEngine], so this one does not.
            String line = diagnostic.severity().name().toLowerCase(Locale.ROOT)
                    + " in " + stage + ": " + diagnostic;
            if (diagnostic.severity() == Diagnostic.Severity.ERROR) {
                getLogger().warning(line);
            } else {
                getLogger().info(line);
            }
            if (!(to instanceof org.bukkit.command.ConsoleCommandSender)) {
                to.sendMessage("[RPEngine] " + line);
            }
        }
    }

    /** "1 item", "2 items". Cheap, and its absence is the sort of thing that reads as unfinished. */
    private static String plural(int count, String noun) {
        return count + " " + noun + (count == 1 ? "" : "s");
    }

    /**
     * Which bundles a player should be holding.
     *
     * <p>One bundle, from the config, and that is the whole policy for now.
     * Per-world and per-permission selection is a server's decision rather
     * than ours, so it arrives as an API rather than as a guess.
     */
    private List<BuiltPack> desiredFor(Player player) {
        if (defaultBundle.isEmpty()) {
            return List.of();
        }
        for (BuiltPack pack : built) {
            if (pack.bundle().equals(defaultBundle)) {
                return List.of(pack);
            }
        }
        return List.of();
    }

    /** A radius a human typed, kept sane. Scanning a whole world is not a command. */
    private static double parseRadius(String text) {
        try {
            return Math.max(1, Math.min(128, Double.parseDouble(text.trim())));
        } catch (NumberFormatException e) {
            return 16;
        }
    }

    /** An amount a human typed. Anything unparseable is one, never a crash. */
    private static int parseAmount(String text) {
        try {
            return Math.max(1, Math.min(99, Integer.parseInt(text.trim())));
        } catch (NumberFormatException e) {
            return 1;
        }
    }

    @EventHandler
    public void onJoin(PlayerJoinEvent event) {
        delivery.apply(event.getPlayer(), desiredFor(event.getPlayer()));
    }

    @EventHandler
    public void onQuit(PlayerQuitEvent event) {
        overlays.clear(event.getPlayer());
        // A client drops its packs on disconnect, so believing otherwise would
        // mean sending nothing to somebody who has nothing.
        sessions.forget(event.getPlayer().getUniqueId());
    }

    /**
     * Every subcommand, and what each one's first argument can be.
     *
     * <p>One list rather than a switch per arity: the subcommands themselves
     * complete from its keys, so a subcommand cannot be added without also
     * being discoverable. See {@link Completions} for why that is a rule.
     */
    private static final List<String> SUBCOMMANDS = List.of(
            "reload", "info", "bundles", "items", "give", "models", "purge",
            "sounds", "sound", "icons", "say", "screens", "screen", "hud", "recipes", "push");

    @Override
    public List<String> onTabComplete(CommandSender sender, Command command, String alias, String[] args) {
        if (args.length <= 1) {
            return Completions.matching(args.length == 0 ? "" : args[0], SUBCOMMANDS);
        }
        String sub = args[0].toLowerCase(Locale.ROOT);
        if (args.length == 2) {
            switch (sub) {
                case "give":
                    return Completions.matchingIds(args[1], items.ids());
                case "sound":
                    return Completions.matchingIds(args[1], sounds.ids());
                case "screen":
                    return Completions.matchingIds(args[1], overlays.screenIds());
                case "hud": {
                    List<String> options = new ArrayList<>(
                            Completions.matchingIds(args[1], overlays.hudIds()));
                    options.addAll(Completions.matching(args[1], "clear"));
                    return options;
                }
                case "models":
                case "purge":
                    // The radii somebody actually wants, rather than nothing at
                    // all because the argument is a number.
                    return Completions.matching(args[1], "8", "16", "32", "64", "128");
                case "say":
                    // Every icon as a ready-made placeholder, because the
                    // colons are the part people get wrong.
                    return Completions.matchingIds(args[1], icons.ids()).stream()
                            .map(id -> ":" + id + ":").toList();
                default:
                    return List.of();
            }
        }
        if (args.length == 3 && sub.equals("give")) {
            return Completions.matching(args[2], "1", "8", "16", "64");
        }
        return List.of();
    }

    @Override
    public boolean onCommand(CommandSender sender, Command command, String label, String[] args) {
        String sub = args.length == 0 ? "info" : args[0].toLowerCase(Locale.ROOT);
        switch (sub) {
            case "reload":
                // config.yml too. Reloading the content but not the settings
                // is the sort of half-reload that has somebody restarting the
                // server anyway and wondering why the command exists.
                reloadConfig();
                defaultBundle = getConfig().getString("default-bundle", "");
                rebuild(sender);
                return true;
            case "bundles":
                if (built.isEmpty()) {
                    sender.sendMessage("[RPEngine] No bundles built.");
                }
                for (BuiltPack pack : built) {
                    sender.sendMessage("[RPEngine] " + pack.bundle() + "  " + pack.entries() + " files, "
                            + pack.size() + " bytes, " + pack.sha1().substring(0, 8)
                            + "  " + host.url(pack.bundle()).orElse("not served"));
                }
                return true;
            case "give": {
                if (args.length < 2) {
                    sender.sendMessage("[RPEngine] /rpengine give <id> [amount]");
                    return true;
                }
                if (!(sender instanceof Player)) {
                    sender.sendMessage("[RPEngine] Only a player can be given an item.");
                    return true;
                }
                int amount = args.length > 2 ? parseAmount(args[2]) : 1;
                Optional<ItemStack> stack = ContentId.parse(args[1]).flatMap(id -> items.create(id, amount));
                if (stack.isEmpty()) {
                    sender.sendMessage("[RPEngine] No item called " + args[1] + ".");
                    return true;
                }
                ((Player) sender).getInventory().addItem(stack.get());
                sender.sendMessage("[RPEngine] Gave " + amount + " " + args[1] + ".");
                return true;
            }
            case "items":
                if (items.ids().isEmpty()) {
                    sender.sendMessage("[RPEngine] No items loaded.");
                }
                for (ContentId id : items.ids()) {
                    ItemInfo info = items.info(id).orElseThrow();
                    sender.sendMessage("[RPEngine] " + id + "  " + info.material()
                            + (info.model().isPresent() ? "  model " + info.model().get() : ""));
                }
                return true;
            case "models": {
                if (!(sender instanceof Player)) {
                    sender.sendMessage("[RPEngine] Only a player can look around them.");
                    return true;
                }
                Player looking = (Player) sender;
                double radius = args.length > 1 ? parseRadius(args[1]) : 16;
                java.util.List<org.bukkit.entity.Interaction> found =
                        placements.near(looking.getLocation(), radius);
                sender.sendMessage("[RPEngine] " + plural(found.size(), "model")
                        + " within " + (int) radius + " blocks.");
                for (org.bukkit.entity.Interaction hitbox : found) {
                    org.bukkit.Location at = hitbox.getLocation();
                    sender.sendMessage("[RPEngine] " + placements.idOf(hitbox).map(Object::toString).orElse("?")
                            + "  " + at.getBlockX() + " " + at.getBlockY() + " " + at.getBlockZ()
                            + (placements.isOrphan(hitbox) ? "  (orphan)" : ""));
                }
                return true;
            }
            case "purge": {
                if (!(sender instanceof Player)) {
                    sender.sendMessage("[RPEngine] Only a player can purge around them.");
                    return true;
                }
                Player around = (Player) sender;
                double radius = args.length > 1 ? parseRadius(args[1]) : 16;
                int removed = 0;
                for (org.bukkit.entity.Interaction hitbox : placements.near(around.getLocation(), radius)) {
                    // Orphans only. Purging models a pack still defines would
                    // be a demolition command wearing a cleanup command's name.
                    if (!placements.isOrphan(hitbox)) {
                        continue;
                    }
                    placements.idOf(hitbox).ifPresent(id -> placements.remove(hitbox, id, around, false));
                    removed++;
                }
                sender.sendMessage("[RPEngine] Removed " + plural(removed, "orphan")
                        + " within " + (int) radius + " blocks. Models a pack still defines were left alone.");
                return true;
            }
            case "sound": {
                if (args.length < 2) {
                    sender.sendMessage("[RPEngine] /rpengine sound <id>");
                    return true;
                }
                if (!(sender instanceof Player)) {
                    sender.sendMessage("[RPEngine] Only a player can be played a sound.");
                    return true;
                }
                boolean played = ContentId.parse(args[1])
                        .map(id -> sounds.play((Player) sender, id)).orElse(Boolean.FALSE);
                sender.sendMessage(played
                        ? "[RPEngine] Played " + args[1] + "."
                        : "[RPEngine] No sound called " + args[1] + ".");
                return true;
            }
            case "icons":
                if (icons.ids().isEmpty()) {
                    sender.sendMessage("[RPEngine] No icons loaded.");
                }
                for (ContentId id : icons.ids()) {
                    sender.sendMessage("[RPEngine] " + id + "  "
                            + icons.character(id).orElse("?") + "  :" + id + ":");
                }
                return true;
            case "say": {
                // Proof the placeholder works in ordinary text, which is the
                // whole point of putting the glyphs in the default font.
                if (args.length < 2) {
                    sender.sendMessage("[RPEngine] /rpengine say <text with :namespace:id: in it>");
                    return true;
                }
                sender.sendMessage(icons.format(String.join(" ",
                        java.util.Arrays.copyOfRange(args, 1, args.length))));
                return true;
            }
            case "screen": {
                if (args.length < 2 || !(sender instanceof Player)) {
                    sender.sendMessage("[RPEngine] /rpengine screen <id>, as a player.");
                    return true;
                }
                boolean opened = ContentId.parse(args[1])
                        .flatMap(id -> overlays.open((Player) sender, id)).isPresent();
                if (!opened) {
                    sender.sendMessage("[RPEngine] No screen called " + args[1] + ".");
                }
                return true;
            }
            case "hud": {
                if (args.length < 2 || !(sender instanceof Player)) {
                    sender.sendMessage("[RPEngine] /rpengine hud <id|clear>, as a player.");
                    return true;
                }
                if (args[1].equalsIgnoreCase("clear")) {
                    overlays.clear((Player) sender);
                    sender.sendMessage("[RPEngine] Cleared.");
                    return true;
                }
                boolean drawn = ContentId.parse(args[1])
                        .map(id -> overlays.draw((Player) sender, id)).orElse(Boolean.FALSE);
                if (!drawn) {
                    sender.sendMessage("[RPEngine] No HUD called " + args[1] + ".");
                }
                return true;
            }
            case "screens":
                for (ContentId id : overlays.screenIds()) {
                    sender.sendMessage("[RPEngine] " + id + "  "
                            + overlays.screen(id).map(o -> o.container()).orElse("?"));
                }
                for (ContentId id : overlays.hudIds()) {
                    sender.sendMessage("[RPEngine] " + id + "  "
                            + overlays.hud(id).map(o -> o.slot().name().toLowerCase(Locale.ROOT)).orElse("?"));
                }
                if (overlays.screenIds().isEmpty() && overlays.hudIds().isEmpty()) {
                    sender.sendMessage("[RPEngine] No screens or HUDs loaded.");
                }
                return true;
            case "recipes":
                if (recipes.size() == 0) {
                    sender.sendMessage("[RPEngine] No recipes registered.");
                }
                for (ContentId id : recipeIds) {
                    sender.sendMessage("[RPEngine] " + id);
                }
                return true;
            case "sounds":
                if (sounds.ids().isEmpty()) {
                    sender.sendMessage("[RPEngine] No sounds loaded.");
                }
                for (ContentId id : sounds.ids()) {
                    sender.sendMessage("[RPEngine] " + id + "  "
                            + sounds.info(id).map(s -> s.category()).orElse("?"));
                }
                return true;
            case "push":
                if (!(sender instanceof Player)) {
                    sender.sendMessage("[RPEngine] Only a player can be pushed a pack.");
                    return true;
                }
                Player player = (Player) sender;
                sessions.forget(player.getUniqueId());
                sender.sendMessage("[RPEngine] " + (delivery.apply(player, desiredFor(player))
                        ? "Sent." : "Nothing to send."));
                return true;
            default:
                sender.sendMessage("[RPEngine] " + plural(registry.ids().size(), "id") + " across "
                        + plural(registry.namespaces().size(), "namespace") + ", "
                        + plural(built.size(), "bundle") + ".");
                List<String> kinds = new ArrayList<>();
                for (ContentKind kind : ContentKind.values()) {
                    int count = registry.ids(kind).size();
                    if (count > 0) {
                        kinds.add(plural(count, kind.name().toLowerCase(Locale.ROOT)));
                    }
                }
                sender.sendMessage("[RPEngine] " + (kinds.isEmpty() ? "nothing loaded" : String.join(", ", kinds)));
                sender.sendMessage("[RPEngine] /rpengine reload | bundles | items | give <id> [n]");
                sender.sendMessage("[RPEngine] /rpengine models [radius] | purge [radius] | push");
                sender.sendMessage("[RPEngine] /rpengine sounds | sound <id> | icons | say <text>");
                sender.sendMessage("[RPEngine] /rpengine recipes");
                sender.sendMessage("[RPEngine] /rpengine screens | screen <id> | hud <id|clear>");
                return true;
        }
    }
}
