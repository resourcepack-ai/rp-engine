    @Test
    void thePlayerWearsTheHighestPriorityTagTheyHold() throws IOException {
        write("mypack/fonts/ranks.yml", """
                owner:
                  priority: 100
                  tag:
                    text: OWNER
                vip:
                  priority: 10
                  tag:
                    text: VIP
                staff/mod:
                  priority: 50
                  tag:
                    text: MOD
                coin:
                  file: coin
                """);
        IconDefinitions.Result result = IconDefinitions.parse(load());
        RankTagWearers wearers = new RankTagWearers();
        wearers.replace(result);

        ContentId owner = ContentId.parse("mypack:owner").orElseThrow();
        ContentId vip = ContentId.parse("mypack:vip").orElseThrow();
        ContentId mod = ContentId.parse("mypack:staff/mod").orElseThrow();
        assertEquals("rpengine.tag.mypack.owner", RankTagWearers.permission(owner));
        assertEquals("rpengine.tag.mypack.staff.mod", RankTagWearers.permission(mod));
        assertEquals(3, wearers.permissions().size(), "one node per tag, none for a plain icon");

        java.util.Set<String> held = new java.util.HashSet<>(List.of("rpengine.tag.mypack.vip", "rpengine.tag.mypack.staff.mod"));
        assertEquals(java.util.Optional.of(mod), wearers.tagOf(held::contains), "MOD outranks VIP");
        held.add("rpengine.tag.mypack.owner");
        assertEquals(java.util.Optional.of(owner), wearers.tagOf(held::contains));
        assertEquals(java.util.Optional.of(vip), wearers.tagOf("rpengine.tag.mypack.vip"::equals));
        assertTrue(wearers.tagOf(node -> false).isEmpty(), "holding none is wearing none");
    }

    @Test
    void anAscentWinsOverTheCentredOne() throws IOException {
        write("mypack/fonts/ranks.yml", """
                vip:
                  ascent: 7
                  tag:
                    text: VIP
                    scale: 2
                """);
        IconInfo vip = IconDefinitions.parse(load()).icons().get(ContentId.parse("mypack:vip").orElseThrow());
        assertEquals(18, vip.height());
        assertEquals(7, vip.ascent());
    }
