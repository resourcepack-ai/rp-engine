    private static final String DIGITS = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ";

    // ---- the same pixels as Studio ------------------------------------------

    /**
     * Every fixture ResourcePack AI Studio drew with its rank tag kit, drawn
     * here from the same spec, every frame of it, compared pixel by pixel. This
     * is the whole agreement between the two: a failure names the fixture, the
     * frame and the first pixel that differs.
     */
    @Test
    void everyFixtureDrawsAsStudioDrewIt() throws IOException {
        JsonObject root;
        try (InputStream in = RankTagsTest.class.getResourceAsStream("/rank-tags/fixtures.json")) {
            assertNotNull(in, "rank-tags/fixtures.json is missing; it is generated by Studio's rank tag kit");
            root = JsonParser.parseString(new String(in.readAllBytes(), StandardCharsets.UTF_8)).getAsJsonObject();
        }
        JsonArray fixtures = root.getAsJsonArray("fixtures");
        assertTrue(fixtures.size() > 40, "too few fixtures to mean anything");
        List<String> failures = new ArrayList<>();
        int frames = 0;
        for (JsonElement element : fixtures) {
            JsonObject f = element.getAsJsonObject();
            String name = f.get("name").getAsString();
            RankTags.Spec spec = specOf(f.getAsJsonObject("spec"));
            JsonArray drawnFrames = f.getAsJsonArray("frames");
            if (spec.frames() != drawnFrames.size()) {
                failures.add(name + ": " + spec.frames() + " frames where Studio drew " + drawnFrames.size());
                continue;
            }
            int width = f.get("width").getAsInt();
            int height = f.get("height").getAsInt();
            int digits = f.get("digits").getAsInt();
            JsonArray palette = f.getAsJsonArray("palette");
            for (int frame = 0; frame < drawnFrames.size(); frame++) {
                frames++;
                RankTags.Drawn drawn = RankTags.render(spec, frame);
                if (drawn.width() != width || drawn.height() != height) {
                    failures.add(name + ": " + drawn.width() + "x" + drawn.height() + " where Studio drew " + width + "x" + height);
                    break;
                }
                if (frame == 0 && drawn.ascent() != f.get("ascent").getAsInt()) {
                    failures.add(name + ": ascent " + drawn.ascent() + " where Studio has " + f.get("ascent").getAsInt());
                }
                JsonArray rows = drawnFrames.get(frame).getAsJsonArray();
                String first = firstDifference(drawn, rows, palette, digits);
                if (first != null) {
                    failures.add(name + ", frame " + frame + ": " + first);
                    break;
                }
            }
        }
        assertTrue(failures.isEmpty(), String.join("\n", failures));
        assertTrue(frames > fixtures.size(), "no fixture is animated");
    }

    private static String firstDifference(RankTags.Drawn drawn, JsonArray rows, JsonArray palette, int digits) {
        for (int y = 0; y < drawn.height(); y++) {
            String row = rows.get(y).getAsString();
            for (int x = 0; x < drawn.width(); x++) {
                int index = digits == 1
                        ? DIGITS.indexOf(row.charAt(x))
                        : DIGITS.indexOf(row.charAt(x * 2)) * DIGITS.length() + DIGITS.indexOf(row.charAt(x * 2 + 1));
                String colour = palette.get(index).getAsString();
                int expected = colour.equals("transparent") ? 0 : 0xff000000 | Integer.parseInt(colour.substring(1), 16);
                if (drawn.at(x, y) != expected) {
                    return "pixel " + x + "," + y + " is " + Integer.toHexString(drawn.at(x, y))
                            + " where Studio drew " + Integer.toHexString(expected);
                }
            }
        }
        return null;
    }

    /** Studio's stored spec (camelCase, hex strings, the kit's defaults where a field is absent) as the engine's. */
    private static RankTags.Spec specOf(JsonObject s) {
        return new RankTags.Spec(
                s.get("text").getAsString(),
                string(s, "shape", "rect"),
                string(s, "face", "flat"),
                hex(s, "fill"),
                optionalHex(s, "fill2"),
                optionalHex(s, "fill3"),
                s.has("border") && !s.get("border").isJsonNull() ? hex(s, "border") : null,
                s.has("border") && s.get("border").isJsonNull(),
                optionalHex(s, "rim"),
                s.has("lip") && s.get("lip").getAsBoolean(),
                hex(s, "ink"),
                optionalHex(s, "ink2"),
                optionalHex(s, "accent"),
                string(s, "effect", "shadow"),
                optionalHex(s, "effectColor"),
                s.has("icon") ? s.get("icon").getAsString() : null,
                s.has("iconStyle") ? s.get("iconStyle").getAsString() : null,
                optionalHex(s, "iconFill"),
                s.has("pad") ? s.get("pad").getAsInt() : null,
                string(s, "anim", "none"),
                s.get("scale").getAsInt(),
                s.get("offset").getAsInt());
    }

    private static String string(JsonObject s, String key, String fallback) {
        return s.has(key) ? s.get(key).getAsString() : fallback;
    }

    private static int hex(JsonObject s, String key) {
        return Integer.parseInt(s.get(key).getAsString().substring(1), 16);
    }

    private static Integer optionalHex(JsonObject s, String key) {
        return s.has(key) && !s.get(key).isJsonNull() ? hex(s, key) : null;
    }

