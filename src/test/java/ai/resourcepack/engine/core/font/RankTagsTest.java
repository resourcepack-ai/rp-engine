    @Test
    void theNewTagIsOneChatLineTall() {
        RankTags.Drawn drawn = RankTags.render(RankTags.Spec.defaults("OWNER"));
        assertEquals(9, drawn.height(), "border + a row of face + five-row capitals + a row of face + border");
        assertEquals(8, drawn.ascent(), "fills the chat line's nine rows exactly");
    }

    @Test
    void coloursAreHexOrTheGamesNames() {
        assertEquals(0xe53935, RankTags.colour("#e53935").orElseThrow());
        assertEquals(0xe53935, RankTags.colour("E53935").orElseThrow());
        assertEquals(0xffaa00, RankTags.colour("gold").orElseThrow());
        assertEquals(0xaa0000, RankTags.colour("dark red").orElseThrow());
        assertEquals(0xff0000, RankTags.colour("#f00").orElseThrow());
        assertTrue(RankTags.colour("reddish").isEmpty());
    }

    @Test
    void theFontSetsCapitalsAndLeavesOutWhatItLacks() {
        assertTrue(RankTags.covers('A'));
        assertTrue(RankTags.covers('a'), "lower case is set as capitals");
        assertTrue(RankTags.covers('+'));
        assertTrue(RankTags.covers(' '));
        assertFalse(RankTags.covers('é'));
        assertEquals("Caf", RankTags.normalizeText("  Café\t"), "printable ASCII, as Studio keeps it");
        assertEquals(RankTags.MAX_TEXT, RankTags.normalizeText("A".repeat(40)).length());
    }

    @Test
    void aBorderlessPulseIsStill() {
        RankTags.Spec pulse = new RankTags.Spec("CALM", "round", "flat", 0x3a6b4b, null, null, null, true, null, false,
                0xffffff, null, null, "shadow", null, null, null, null, null, "pulse", 1, 0);
        assertFalse(pulse.animated(), "a pulse lights the border, and there is none");
        assertEquals(1, pulse.frames());
        RankTags.Spec glint = new RankTags.Spec("VIP", "round", "gloss", 0xffb300, null, null, null, false, null, false,
                0xffffff, null, null, "outline", null, null, null, null, null, "glint", 1, 0);
        assertEquals(RankTags.FRAMES, glint.frames());
    }

    // ---- in a content folder ------------------------------------------------

    @TempDir
    Path root;

    private Path content;
    private Path out;

    @BeforeEach
    void setUp() throws IOException {
        content = root.resolve("content");
        out = root.resolve("out");
        Files.createDirectories(content);
        write("mypack/pack.yml", "{}\n");
    }

    private void write(String path, String text) throws IOException {
        Path file = content.resolve(path);
        Files.createDirectories(file.getParent());
        Files.writeString(file, text, StandardCharsets.UTF_8);
    }

    private LoadReport load() {
        return new ContentFolderLoader(new ContentRegistryImpl()).load(content, ContentSource.AUTHORED);
    }

    private Map<String, byte[]> zip() throws IOException {
        BuildReport report = new PackBuilder().with(new FontAssets()).build(content, out, load());
        Map<String, byte[]> entries = new LinkedHashMap<>();
        try (InputStream in = Files.newInputStream(report.pack("main").orElseThrow().file());
             ZipInputStream zin = new ZipInputStream(in)) {
            ZipEntry entry;
            while ((entry = zin.getNextEntry()) != null) {
                entries.put(entry.getName(), zin.readAllBytes());
            }
        }
        return entries;
    }

    @Test
    void aTagIsAnIconTheBuildDraws() throws IOException {
        write("mypack/fonts/ranks.yml", """
                owner:
                  tag:
                    text: OWNER
                    background: "#e53935"
                admin:
                  tag:
                    text: ADMIN
                    background: dark_red
                    shape: pill
                    face: gloss
                    effect: outline
                    icon: shield
                    icon-style: tile
                """);
        IconDefinitions.Result result = IconDefinitions.parse(load());
        assertTrue(result.diagnostics().isEmpty(), result.diagnostics().toString());
        IconInfo owner = result.icons().get(ContentId.parse("mypack:owner").orElseThrow());
        assertNotNull(owner);
        assertEquals(9, owner.height());
        assertEquals(8, owner.ascent());
        assertEquals("rank_tags/owner", owner.file());
        assertFalse(owner.animated());
        RankTags.Spec ownerSpec = result.tags().get(owner.id());
        assertEquals("round", ownerSpec.shape(), "the classic rounded tag unless it says otherwise");
        assertEquals(0xe53935, ownerSpec.fill());
        assertEquals(null, ownerSpec.border(), "a border left to the kit, a darker background");

        Map<String, byte[]> zip = zip();
        byte[] png = zip.get("assets/mypack/textures/font/rank_tags/owner.png");
        assertNotNull(png, "the build writes the drawing where the provider points");
        BufferedImage image = ImageIO.read(new ByteArrayInputStream(png));
        RankTags.Drawn drawn = RankTags.render(ownerSpec);
        assertEquals(drawn.width(), image.getWidth());
        assertEquals(drawn.height(), image.getHeight());
        for (int y = 0; y < drawn.height(); y++) {
            for (int x = 0; x < drawn.width(); x++) {
                assertEquals(drawn.at(x, y), image.getRGB(x, y), "pixel " + x + "," + y);
            }
        }
        String font = new String(zip.get(FontAssets.DEFAULT_FONT), StandardCharsets.UTF_8);
        assertTrue(font.contains("\"file\": \"mypack:font/rank_tags/owner.png\""), font);
        assertTrue(font.contains("\"height\": 9"), font);
    }

    @Test
    void anAnimatedTagIsItsFramesWhichTheServerPlays() throws IOException {
        write("mypack/fonts/ranks.yml", """
                legend:
                  tag:
                    text: LEGEND
                    background: "#2a1640"
                    face: sparkle
                    animation: twinkle
                zz:
                  tag:
                    text: NEXT
                """);
        IconDefinitions.Result result = IconDefinitions.parse(load());
        assertTrue(result.diagnostics().isEmpty(), result.diagnostics().toString());
        IconInfo legend = result.icons().get(ContentId.parse("mypack:legend").orElseThrow());
        IconInfo next = result.icons().get(ContentId.parse("mypack:zz").orElseThrow());
        assertTrue(legend.animated());
        assertEquals(RankTags.FRAMES, legend.frames());
        assertEquals(RankTags.FPS, legend.fps());
        assertEquals(RankTags.FRAMES, legend.rows(), "a strip, one row a frame");
        assertEquals(9, legend.height(), "a frame's height, not the strip's");
        assertEquals(legend.codepoint() + RankTags.FRAMES, next.codepoint(), "sixteen codepoints, one a frame");

        Map<String, byte[]> zip = zip();
        BufferedImage strip = ImageIO.read(new ByteArrayInputStream(zip.get("assets/mypack/textures/font/rank_tags/legend.png")));
        RankTags.Spec spec = result.tags().get(legend.id());
        RankTags.Drawn first = RankTags.render(spec, 0);
        assertEquals(first.width(), strip.getWidth());
        assertEquals(first.height() * RankTags.FRAMES, strip.getHeight());
        boolean moves = false;
        for (int frame = 0; frame < RankTags.FRAMES; frame++) {
            RankTags.Drawn drawn = RankTags.render(spec, frame);
            for (int y = 0; y < drawn.height(); y++) {
                for (int x = 0; x < drawn.width(); x++) {
                    assertEquals(drawn.at(x, y), strip.getRGB(x, frame * drawn.height() + y), "frame " + frame + " pixel " + x + "," + y);
                    moves |= drawn.at(x, y) != first.at(x, y);
                }
            }
        }
        assertTrue(moves, "the frames differ");
        String font = new String(zip.get(FontAssets.DEFAULT_FONT), StandardCharsets.UTF_8);
        assertTrue(font.contains("\"height\": 9"), "the provider draws one frame at a time: " + font);
    }

    @Test
    void mistakesAreWarningsAndTheTagStillDraws() {
        List<Diagnostic> diagnostics = new ArrayList<>();
        var node = ai.resourcepack.engine.api.DefinitionNode.of(Map.of(
                "text", "VIP", "background", "reddish", "shape", "blob", "face", "shiny", "effect", "glow",
                "animation", "spin", "icon", "nope", "scale", 9));
        RankTags.Spec spec = RankTags.parse(node, "mypack/fonts", "vip", diagnostics).orElseThrow();
        assertEquals(7, diagnostics.size(), diagnostics.toString());
        assertEquals("round", spec.shape());
        assertEquals("flat", spec.face());
        assertEquals("shadow", spec.effect());
        assertEquals("none", spec.animation());
        assertEquals(null, spec.icon());
        assertEquals(RankTags.MAX_SCALE, spec.scale());
        assertEquals(0xd9413b, spec.fill());
    }

    @Test
    void studiosOwnFontsAndTexturesAreToldAndDrawnWithout() {
        List<Diagnostic> diagnostics = new ArrayList<>();
        var node = ai.resourcepack.engine.api.DefinitionNode.of(Map.of(
                "text", "Sr.Mod", "font", "mc", "face", "texture", "border", "none"));
        RankTags.Spec spec = RankTags.parse(node, "mypack/fonts", "mod", diagnostics).orElseThrow();
        assertEquals(2, diagnostics.size(), diagnostics.toString());
        assertEquals("flat", spec.face());
        assertTrue(spec.noBorder());
        assertEquals(9 - 2, RankTags.render(spec).height(), "the block capitals, and no border round them");
    }

